// 用户类型
export interface User {
  id: string;
  nickname: string;
  passwordHash: string;
  avatar: string;
  // 模块独立经验值系统
  moduleData: {
    math: { exp: number; level: number; selectedTitle: string | null };
  };
  // 用户选择的主展示模块（决定显示哪个模块的称号）
  displayCategory?: 'math';
  // 收藏的帖子ID列表
  favoritePosts?: string[];
  // 收藏的每日一题ID列表
  favoriteQuestions?: string[];
  // 关注列表
  following?: string[];
  // 个性签名
  bio?: string;
  // 个人主页封面背景图（data URL 或 http 链接）
  coverImage?: string;
  // 隐私设置
  privacy?: {
    showFollowing: boolean;  // 是否显示关注列表
    showFollowers: boolean;  // 是否显示粉丝列表
    showBio: boolean;        // 是否显示个性签名
  };
  // π力系统数据
  piPower: {
    currentPi: number;           // 当前总π力
    monthlyPi: number;           // 本月π力
    totalAnswered: number;       // 累计答对题数
    monthlyAnswered: number;     // 本月答对题数
    lastAnswerDate: string | null; // 最后答题日期
    currentStreak: number;       // 连续答对天数
    monthlyResetDate: string;    // 下次清零日期
    dailyAttempts: Record<string, number>; // 每日尝试次数（日期->次数）
    questionPi?: Record<string, number>;   // 每题已获得的π力（题目ID->π值，每题上限2π）
  };
  // 用户位置信息
  location?: {
    province: string;  // 省份
    city?: string;     // 城市（可选）
    updatedAt: string; // 更新时间
  };
  // 欧拉称号历史记录
  eulerTitleHistory: {
    id: string;
    title: string;      // 称号名称
    province?: string;  // 省份
    rankType: 'province' | 'global';
    rank: number;
    obtainedAt: string;
    month: string;      // YYYY-MM
  }[];
  // 当前生效的欧拉称号（每月评选）
  currentEulerTitle?: {
    title: string;
    province?: string;
    rankType: 'province' | 'global';
    rank: number;
    obtainedAt: string;
    month: string;
  };
  // 兼容旧数据，保留以下字段
  level?: number;
  experience?: number;
  title?: string;
  frame?: string;
  isAdmin: boolean;
  createdAt: string;
  lastLoginAt: string;
}

